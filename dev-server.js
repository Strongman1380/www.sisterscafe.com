// API Handlers
function ordersHandler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'GET, POST, PUT, DELETE, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization');

  if (req.method === 'OPTIONS') {
    res.writeHead(200);
    res.end();
    return;
  }

  if (req.method === 'GET') {
    const sortedOrders = orders.sort((a, b) => new Date(b.created_at) - new Date(a.created_at));
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify(sortedOrders));
  } else {
    res.writeHead(405, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: 'Method not allowed' }));
  }
}

async function addOrderHandler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'GET, POST, PUT, DELETE, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization');

  if (req.method === 'OPTIONS') {
    res.writeHead(200);
    res.end();
    return;
  }

  if (req.method !== 'POST') {
    res.writeHead(405, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: 'Method not allowed' }));
    return;
  }

  try {
    const order = req.body;
    
    if (!order.id || !order.customer_name || !order.amount_total) {
      res.writeHead(400, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ error: 'Missing required order fields' }));
      return;
    }
    
    order.is_demo = true;
    order.created_at = order.created_at || new Date().toISOString();
    order.updated_at = new Date().toISOString();
    
    orders.push(order);
    
    console.log(`Demo order created: ${order.id} for ${order.customer_name} ($${(order.amount_total / 100).toFixed(2)})`);
    
    // Send notifications for demo orders
    try {
      await sendOrderNotificationEmail(order);
      await sendOrderNotificationSMS(order);
      
      if (order.sms_notifications && order.customer_phone) {
        await sendCustomerNotificationSMS(order, `Thank you for your order #${order.id}! We've received your order for $${(order.amount_total / 100).toFixed(2)} and will start preparing it shortly. You'll receive updates via SMS.`);
      }
      
      console.log(`✅ All notifications sent for order ${order.id}`);
    } catch (error) {
      console.error('❌ Error sending notifications:', error);
    }
    
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ 
      success: true, 
      order: order,
      message: 'Demo order created successfully with notifications sent'
    }));
    
  } catch (error) {
    console.error('Error creating demo order:', error);
    res.writeHead(500, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: 'Internal server error' }));
  }
}


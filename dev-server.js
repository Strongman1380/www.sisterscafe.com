/**
 * Handle Stripe Connect API requests by dynamically importing the appropriate module
 * This allows us to use ES modules in a CommonJS environment
 */
async function handleConnectAPI(req, res, apiType) {
  try {
    // Parse query parameters for GET requests
    if (req.method === 'GET') {
      const parsedUrl = url.parse(req.url, true);
      req.query = parsedUrl.query;
    }

    // Dynamically import the appropriate Connect API module
    const modulePath = path.join(__dirname, 'api', 'connect', `${apiType}.js`);
    
    // Check if the module file exists
    if (!fs.existsSync(modulePath)) {
      res.writeHead(404, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ error: `Connect API module not found: ${apiType}` }));
      return;
    }

    // Import the module dynamically
    const module = await import(`file://${modulePath}`);
    const handler = module.default;

    if (typeof handler !== 'function') {
      res.writeHead(500, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ error: `Invalid Connect API module: ${apiType}` }));
      return;
    }

    // Call the handler with req and res
    await handler(req, res);

  } catch (error) {
    console.error(`Connect API Error (${apiType}):`, error);
    res.writeHead(500, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ 
      error: 'Connect API error',
      message: error.message 
    }));
  }
}

const server = http.createServer((req, res) => {
  const parsedUrl = url.parse(req.url, true);
  const pathname = parsedUrl.pathname;
  
  console.log(`${req.method} ${pathname}`);
  
  // Handle API requests
  if (pathname.startsWith('/api/')) {
    handleAPIRequest(req, res, pathname);
    return;
  }
  
  // Handle static files
  let filePath = pathname;
  
  // Default to index.html for root
  if (filePath === '/') {
    filePath = '/index.html';
  }
  
  // Remove leading slash
  if (filePath.startsWith('/')) {
    filePath = filePath.substring(1);
  }
  
  serveStaticFile(res, filePath);
});


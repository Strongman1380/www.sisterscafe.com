// MIME types
const mimeTypes = {
  '.html': 'text/html',
  '.js': 'text/javascript',
  '.css': 'text/css',
  '.json': 'application/json',
  '.png': 'image/png',
  '.jpg': 'image/jpg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon'
};

function getMimeType(filePath) {
  const ext = path.extname(filePath).toLowerCase();
  return mimeTypes[ext] || 'application/octet-stream';
}

function serveStaticFile(res, filePath) {
  const fullPath = path.join(ROOT_DIR, filePath);
  
  fs.readFile(fullPath, (err, data) => {
    if (err) {
      res.writeHead(404, { 'Content-Type': 'text/plain' });
      res.end('File not found');
      return;
    }
    
    const mimeType = getMimeType(fullPath);
    res.writeHead(200, { 'Content-Type': mimeType });
    res.end(data);
  });
}

function handleAPIRequest(req, res, pathname) {
  // Set CORS headers for all API requests
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'GET, POST, PUT, DELETE, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization');
  
  if (req.method === 'OPTIONS') {
    res.writeHead(200);
    res.end();
    return;
  }

  // Parse request body for POST requests
  if (req.method === 'POST') {
    let body = '';
    req.on('data', chunk => {
      body += chunk.toString();
    });
    req.on('end', () => {
      try {
        req.body = JSON.parse(body);
      } catch (e) {
        req.body = {};
      }
      routeAPIRequest(req, res, pathname);
    });
  } else {
    routeAPIRequest(req, res, pathname);
  }
}

function routeAPIRequest(req, res, pathname) {
  try {
    if (pathname === '/api/orders') {
      ordersHandler(req, res);
    } else if (pathname === '/api/demo/add-order') {
      addOrderHandler(req, res);
    } else if (pathname === '/api/demo/clear-orders') {
      clearOrdersHandler(req, res);
    } else if (pathname.match(/^\/api\/orders\/[^\/]+\/status$/)) {
      // Extract order ID from path
      const orderId = pathname.split('/')[3];
      req.query = { id: orderId };
      statusHandler(req, res);
    } else if (pathname === '/api/connect/accounts') {
      // Handle Stripe Connect accounts API
      handleConnectAPI(req, res, 'accounts');
    } else if (pathname === '/api/connect/account-links') {
      // Handle Stripe Connect account links API
      handleConnectAPI(req, res, 'account-links');
    } else if (pathname === '/api/connect/products') {
      // Handle Stripe Connect products API
      handleConnectAPI(req, res, 'products');
    } else if (pathname === '/api/connect/checkout') {
      // Handle Stripe Connect checkout API
      handleConnectAPI(req, res, 'checkout');
    } else if (pathname === '/api/create-checkout-session') {
      // Handle regular Stripe checkout session creation
      handleStripeCheckout(req, res);
    } else if (pathname === '/api/webhook') {
      // Handle Stripe webhook
      handleStripeWebhook(req, res);
    } else {
      res.writeHead(404, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ error: 'API endpoint not found' }));
    }
  } catch (error) {
    console.error('API Error:', error);
    res.writeHead(500, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: 'Internal server error' }));
  }
}

/**
 * Handle regular Stripe checkout session creation
 */
async function handleStripeCheckout(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'GET, POST, PUT, DELETE, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization');

  if (req.method === 'OPTIONS') {
    res.writeHead(200);
    res.end();
    return;
  }

  if (req.method !== 'POST') {
    res.writeHead(405, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: 'Method not allowed' }));
    return;
  }

  try {
    // Use the real Stripe API module
    const modulePath = path.join(__dirname, 'api', 'create-checkout-session.js');

    if (!fs.existsSync(modulePath)) {
      res.writeHead(404, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ error: 'Checkout module not found' }));
      return;
    }

    const module = await import(`file://${modulePath}`);
    const handler = module.default;

    if (typeof handler !== 'function') {
      res.writeHead(500, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ error: 'Invalid checkout module' }));
      return;
    }

    // Add headers property to req for the Stripe module
    req.headers = req.headers || {};
    req.headers['x-forwarded-proto'] = 'http';
    req.headers['host'] = `localhost:${PORT}`;

    await handler(req, res);

  } catch (error) {
    console.error('Stripe Checkout Error:', error);
    res.writeHead(500, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({
      error: 'Checkout session error',
      message: error.message
    }));
  }
}

